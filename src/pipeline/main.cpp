/// Parse and dispatch a WebSocket message to the appropriate TimescaleDB writer method.
void process_message(const std::string& raw, market_ingestion::TimescaleWriter& db) {
    try {
        auto j = json::parse(raw);

        // Handle subscription response ack
        if (j.contains("op") && j["op"] == "subscribe") {
            return;
        }

        // Handle pong / heartbeat
        if (j.contains("type") && j["type"] == "pong") return;
        if (j.contains("ret_msg") && j["ret_msg"] == "pong") return;

        // Route by topic
        if (j.contains("topic")) {
            std::string topic = j["topic"];

            if (topic.rfind("orderbook.", 0) == 0) {
                db.insert_orderbook(j);
            } else if (topic.rfind("publicTrade.", 0) == 0) {
                db.insert_trade(j);
            }
        }
    } catch (const std::exception& e) {
        std::cerr << "[ERROR] Failed to parse/insert message: " << e.what() << std::endl;
    }
}

/// Extract the best bid and ask from Bybit orderbook JSON and compute spread as an integer (scaled by 10^8 or similar for fixed-point math)
uint32_t extract_spread_from_json(const json& j) {
    try {
        // Bybit V5 format: {"data": {"b": [["price", "size"], ...], "a": [["price", "size"], ...]} }
        if (j.contains("data") && j["data"].contains("b") && j["data"].contains("a")) {
            auto& bids = j["data"]["b"];
            auto& asks = j["data"]["a"];
            
            if (!bids.empty() && !asks.empty()) {
                // Bybit prices are strings to preserve precision, convert to double/uint
                double best_bid = std::stod(bids[0][0].get<std::string>());
                double best_ask = std::stod(asks[0][0].get<std::string>());
                
                // Calculate spread (multiply by 100 or 10000 to keep integer precision if needed)
                double spread = best_ask - best_bid;
                return static_cast<uint32_t>(spread * 100.0); // Scaled integer for hardware
            }
        }
    } catch (...) {
        // Return 0 on any parsing malformation
    }
    return 0;
}

/// Build the JSON subscription payload for both orderbook and public trade streams.
std::string build_subscription(const std::vector<std::string>& symbols, int depth) {
    std::string msg = "{\"op\": \"subscribe\", \"args\": [";
    for (size_t i = 0; i < symbols.size(); ++i) {
        msg += "\"orderbook." + std::to_string(depth) + "." + symbols[i] + "\"";
        msg += ", ";
        msg += "\"publicTrade." + symbols[i] + "\"";
        if (i < symbols.size() - 1) {
            msg += ", ";
        }
    }
    msg += "]}";
    return msg;
}

int main() {
    try {
        // Target Bybit V5 Public Linear API endpoint.
        const std::string host = "stream.bybit.com";
        const std::string port = "443";
        const std::string target = "/v5/public/linear";

        // Define highly liquid instruments for cross-margin or funding-rate arbitrage.
        // BTCUSDT  = USDT-Margined Perpetual
        // BTC-PERP = USDC-Margined Perpetual
        const std::vector<std::string> symbols = {"BTCUSDT", "BTCPERP"};
        const int depth = 50;

        // Connect to TimescaleDB.
        const char* conn_str = std::getenv("TIMESCALE_CONN");
        if (!conn_str) {
            conn_str = "host=timescaledb port=5432 dbname=market_data user=market password=market";
        }
        market_ingestion::TimescaleWriter db(conn_str);
        if (!db.connected()) {
            std::cerr << "[WARN] TimescaleDB not available – running without database persistence." << std::endl;
        } else {
            db.init_schema();
        }

        // Construct the JSON subscription payload.
        std::string sub_message = build_subscription(symbols, depth);

        // Initialize the core I/O context for network operations.
        net::io_context ioc;

        // Configure the SSL context utilizing TLS v1.2 as the required baseline protocol.
        ssl::context ctx{ssl::context::tlsv12_client};
        
        // TODO(Production): Enforce strict SSL peer verification to prevent MITM attacks.
        // ctx.set_default_verify_paths();
        // ctx.set_verify_mode(ssl::verify_peer);

        // Instantiate the TCP resolver and secure WebSocket stream.
        tcp::resolver resolver{ioc};
        websocket::stream<beast::ssl_stream<tcp::socket>> ws{ioc, ctx};

        // Resolve the host domain to an IP address.
        auto const results = resolver.resolve(host, port);

        // Establish the underlying TCP connection to the resolved endpoint.
        auto ep = net::connect(get_lowest_layer(ws), results);

        // Configure Server Name Indication (SNI) on the SSL stream to ensure correct TLS routing.
        if(! SSL_set_tlsext_host_name(ws.next_layer().native_handle(), host.c_str())) {
            throw beast::system_error(
                beast::error_code(
                    static_cast<int>(::ERR_get_error()),
                    net::error::get_ssl_category()),
                "Failed to configure SNI Hostname");
        }

        // Execute the TLS handshake.
        ws.next_layer().handshake(ssl::stream_base::client);

        // Apply an HTTP decorator to set a custom User-Agent header for the WebSocket upgrade request.
        ws.set_option(websocket::stream_base::decorator(
            [](websocket::request_type& req) {
                req.set(http::field::user_agent, std::string(BOOST_BEAST_VERSION_STRING) + " bybit-arb-client");
            }));

        // Execute the WebSocket protocol upgrade handshake.
        ws.handshake(host, target);
        std::cout << "[INFO] Successfully established secure WebSocket connection to Bybit." << std::endl;

        // Transmit the subscription payload to the exchange.
        ws.write(net::buffer(sub_message));
std::cout << "[DEBUG] Subscription sent: " << sub_message << std::endl;
        std::cout << "[INFO] Transmitted subscription payload: " << sub_message << std::endl;

        Vspread_detector fpga_detector;
        // Initialize signals
        fpga_detector.clk = 0;
        fpga_detector.rst_n = 1; // Assuming active-low reset

        // Metrics tracking
        metrics::MetricsCollector metrics_collector;
        metrics::FiberLatencyConfig fiber_config;
        metrics::BenchmarkReport benchmark;
        uint64_t cycle_count = 0;
        auto start_time = std::chrono::high_resolution_clock::now();

        // Enter the synchronous event loop to process incoming WebSocket messages.
        while (true) {
            beast::flat_buffer buffer;
            ws.read(buffer);
            std::string raw = beast::buffers_to_string(buffer.data());

            if (db.connected()) {
                process_message(raw, db);
            }

            // --- HARDWARE ACCELERATION HOOK ---
            try {
                auto j = json::parse(raw);
                // Determine exchange format and extract spread
                uint32_t current_spread = 0;
                bool is_bybit = false;
                bool is_binance = false;

                // Check for Bybit V5 format: {"topic": "orderbook.XXX", "data": {"b": [...], "a": [...]}}
                if (j.contains("topic") && j["topic"].is_string()) {
                    std::string topic = j["topic"].get<std::string>();
                    if (topic.rfind("orderbook.", 0) == 0 || topic.rfind("publicTrade.", 0) == 0) {
                        is_bybit = true;
                        // Bybit: best bid/ask in j["data"]["b"] and j["data"]["a"]
                        if (j.contains("data") && j["data"].contains("b") && j["data"].contains("a")) {
                            auto& bids = j["data"]["b"];
                            auto& asks = j["data"]["a"];
                            if (!bids.empty() && !asks.empty()) {
                                double best_bid = std::stod(bids[0][0].get<std::string>());
                                double best_ask = std::stod(asks[0][0].get<std::string>());
                                current_spread = static_cast<uint32_t>((best_ask - best_bid) * 100.0);
                            }
                        }
                    else if (topic.rfind("tickers.", 0) == 0) {
                        is_bybit = true;
                        // Bybit ticker format: {"topic": "tickers.BTCUSDT", "data": {"bid1Price": "...", "ask1Price": "..."}}
                        if (j.contains("data")) {
                            auto& data = j["data"];
                            if (data.contains("bid1Price") && data.contains("ask1Price")) {
                                double best_bid = data.value("bid1Price", "0").get<std::string>().empty() ? 0 : std::stod(data["bid1Price"].get<std::string>());
                                double best_ask = data.value("ask1Price", "0").get<std::string>().empty() ? 0 : std::stod(data["ask1Price"].get<std::string>());
                                current_spread = static_cast<uint32_t>((best_ask - best_bid) * 100.0);
                            }
                        }
                    }
                }

                // Check for Binance format: {"topic": "!symbol@orderbook"} or {"b": [...], "a": [...]}
                if (!is_bybit && j.contains("b") && j.contains("a")) {
                    is_binance = true;
                    // Binance: best bid/ask directly in j["b"] and j["a"]
                    if (!j["b"].empty() && !j["a"].empty()) {
                        double best_bid = std::stod(j["b"][0][0].get<std::string>());
                        double best_ask = std::stod(j["a"][0][0].get<std::string>());
                        current_spread = static_cast<uint32_t>((best_ask - best_bid) * 100.0);
                    }
                }

                // Also handle direct bid/ask without topic (Binance sometimes sends raw orderbook)
                if (!is_binance && j.contains("bidPrice") && j.contains("askPrice")) {
                    double best_bid = j["bidPrice"].get<double>();
                    double best_ask = j["askPrice"].get<double>();
                    current_spread = static_cast<uint32_t>((best_ask - best_bid) * 100.0);
                }



                    // Drive AXI-Stream inputs to the Verilated FPGA block
                    fpga_detector.s_axis_tdata = current_spread;
                    fpga_detector.s_axis_tvalid = 1;

                    // Toggle clock to pulse the hardware logic
                    fpga_detector.clk = 0;
                    fpga_detector.eval();
                    
                    fpga_detector.clk = 1;
                    fpga_detector.eval();

                    // Check if hardware fired the ultra-low latency threshold alert!
                    if (fpga_detector.threshold_breached_o) {
                        std::cout << "[ALERT] FPGA detected spread breach! Spread: " 
                                << fpga_detector.current_spread_o << std::endl;
                        
                        // TODO: Trigger instant order dispatch or hedging logic here
                    }
                }
            } catch (...) {
                // Handle parse exceptions safely without breaking the ingestion loop
            }
        }
    } catch(std::exception const& e) {
        std::cerr << "[FATAL] Exception caught: " << e.what() << "\n";
        return EXIT_FAILURE; 
    }
    
    // --- Generate benchmark report ---
        auto end_time = std::chrono::high_resolution_clock::now();
        std::chrono::duration<double> elapsed = end_time - start_time;
        benchmark.timestamp = metrics::MetricsCollector::get_timestamp();
        benchmark.sw.cycles_elapsed = cycle_count;
        benchmark.sw.transactions_processed = 0;
        benchmark.sw.avg_latency_ns = std::numeric_limits<double>::quiet_NaN();
        benchmark.hw = metrics::MetricsCollector::parse_synthesis_report(
            "hardware/rtl/synthesis_report.txt");
        benchmark.latency = metrics_collector.calculate_fiber_latency(
            fiber_config, 0.0, 0.0);
        benchmark.valid = false;

        // === Log program exit ===
        main_log << "[MAIN] Program ending, generating benchmark report" << std::endl;
        exchange_log << "[EXCHANGE] Program ending" << std::endl;
        // Write benchmark report
        std::ofstream report_file("benchmark_report.txt");
        if (report_file.is_open()) {
            report_file << "Market Microstructure Engine Benchmark Report" << std::endl;
            report_file << "======================================" << std::endl;
            report_file << "Timestamp: " << benchmark.timestamp << '\n';
            report_file << "Generic Yosys synthesis parsed: "
                        << (benchmark.hw.generic_synthesis_available ? "yes" : "no") << '\n';
            if (benchmark.hw.generic_synthesis_available) {
                report_file << "Generic cells: " << benchmark.hw.cell_count << '\n'
                            << "Generic wires: " << benchmark.hw.wire_count << '\n';
            }
            report_file << "Target FPGA LUT/FF/carry/BRAM/URAM/DSP usage: not measured\n"
                        << "Post-place-and-route Fmax: not measured\n"
                        << "WNS/WHS timing closure: not measured\n"
                        << "Fiber receive/transmit latency: not measured\n"
                        << "Software latency: not instrumented in this legacy pipeline\n"
                        << "Valid measured end-to-end report: false\n";
            report_file.close();
            std::cout << "[BENCHMARK] Report written to benchmark_report.txt" << std::endl;
        } else {
            std::cerr << "[WARN] Could not write benchmark_report.txt" << std::endl;
        }
        report_file.close();

        return EXIT_SUCCESS;
}
